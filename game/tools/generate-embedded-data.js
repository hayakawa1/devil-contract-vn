const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const publicDir = path.join(root, 'public');

function readText(relativePath) {
  return fs.readFileSync(path.join(publicDir, relativePath), 'utf8');
}

function listFiles(dir, extensions) {
  const absoluteDir = path.join(publicDir, dir);
  return fs.readdirSync(absoluteDir)
    .filter((name) => extensions.includes(path.extname(name).toLowerCase()))
    .sort()
    .map((name) => path.posix.join(dir.replace(/\\/g, '/'), name));
}

const files = {
  'assets/characters.json': readText('assets/characters.json'),
  'public/assets/characters.json': readText('assets/characters.json'),
  'assets/episodes.json': readText('assets/episodes.json'),
  'public/assets/episodes.json': readText('assets/episodes.json')
};

for (const file of [...listFiles('scenarios', ['.ks', '.json']), ...listFiles('scenarios/en', ['.ks'])]) {
  const text = readText(file);
  files[file] = text;
  files[`public/${file}`] = text;
}

const output = [
  '// Generated by tools/generate-embedded-data.js',
  '// Used as a fallback when packaged WebView fetch cannot read local assets.',
  `export const embeddedFiles = ${JSON.stringify(files)};`,
  ''
].join('\n');

fs.writeFileSync(path.join(root, 'embedded-data.js'), output, 'utf8');
